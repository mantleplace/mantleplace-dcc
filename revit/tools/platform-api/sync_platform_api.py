"""Vendor the generated Platform API client, or check that the vendored copy is current.

The Revit plugin calls the Platform API through MantlePlace.PlatformApi, a client generated by
NSwag from the spec the platform serves. Two files are vendored, and both come from this script:

    revit/src/MantlePlace.PlatformApi/Generated/openapi.json         the spec it was generated from
    revit/src/MantlePlace.PlatformApi/Generated/PlatformApiClient.g.cs the generated client

    python revit/tools/platform-api/sync_platform_api.py            # fetch, generate, write
    python revit/tools/platform-api/sync_platform_api.py --check    # fail when either would change
    python revit/tools/platform-api/sync_platform_api.py --spec F   # a local spec file or another URL

The generator is pinned in revit/.config/dotnet-tools.json and restored with `dotnet tool restore`;
it is a build-time tool, so the assemblies the plugin ships still restore no NuGet package. Every
generator option is in GENERATOR_OPTIONS below and nowhere else, so the check and a sync cannot
disagree about what "generated" means. Line endings are LF on every platform.
"""

from __future__ import annotations

import argparse
import difflib
import json
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

SERVED_SPEC = "https://mantle.place/api/v1/openapi.json"

# Python's default user agent is refused by the edge in front of mantle.place; name the caller.
USER_AGENT = "mantleplace-dcc platform-api sync"

REVIT = Path(__file__).resolve().parents[2]
GENERATED = REVIT / "src" / "MantlePlace.PlatformApi" / "Generated"
VENDORED_SPEC = GENERATED / "openapi.json"
VENDORED_CLIENT = GENERATED / "PlatformApiClient.g.cs"

# The client header is applied once, by PlatformTransport, to every request; excluding it here keeps
# it out of every generated signature, so no call site can forget it or send a second one. Optional
# properties are nullable so an absent member reads as absent: a public Quote has no Credit balance,
# which is not a balance of 0 (the corpus case platform.quote.public pins it).
GENERATOR_OPTIONS = [
    "/namespace:MantlePlace.PlatformApi",
    "/className:PlatformApiClient",
    "/JsonLibrary:SystemTextJson",
    "/GenerateNullableReferenceTypes:true",
    "/UseBaseUrl:true",
    "/GenerateBaseUrlProperty:true",
    "/GenerateClientInterfaces:false",
    "/InjectHttpClient:true",
    "/DisposeHttpClient:false",
    "/GenerateExceptionClasses:true",
    "/GenerateOptionalPropertiesAsNullable:true",
    "/ExcludedParameterNames:Mantle-Place-Client",
]


def read_spec(source: str) -> str:
    """The spec as vendored: parsed and re-written with a stable indent, key order kept."""
    if source.startswith(("http://", "https://")):
        request = urllib.request.Request(source, headers={"Accept": "application/json", "User-Agent": USER_AGENT})
        with urllib.request.urlopen(request, timeout=60) as response:  # noqa: S310 - a fixed https URL
            raw = response.read().decode("utf-8")
    else:
        raw = Path(source).read_text(encoding="utf-8")
    return json.dumps(json.loads(raw), indent=2, ensure_ascii=False) + "\n"


def lf(text: str) -> str:
    return text.replace("\r\n", "\n")


# NSwag's System.Text.Json output puts JsonStringEnumConverter<T> on every enum property. That
# converter ignores [EnumMember] and writes the C# name ("Credit") where the spec serves "credit",
# and the framework's fix (JsonStringEnumMemberName) needs .NET 9 while the client targets net8.0.
# MantlePlace.PlatformApi/EnumMemberJsonConverter.cs honours EnumMember; this swaps it in so a
# regeneration keeps the fix.
STOCK_ENUM_CONVERTER = "System.Text.Json.Serialization.JsonStringEnumConverter<"
ENUM_MEMBER_CONVERTER = "MantlePlace.PlatformApi.EnumMemberJsonConverter<"


def honour_enum_member(client_text: str) -> str:
    return client_text.replace(STOCK_ENUM_CONVERTER, ENUM_MEMBER_CONVERTER)


def generate(spec_text: str) -> str:
    """Runs the pinned generator over the spec and returns the client source."""
    subprocess.run(["dotnet", "tool", "restore"], cwd=REVIT, check=True, stdout=subprocess.DEVNULL)
    with tempfile.TemporaryDirectory() as scratch:
        spec_path = Path(scratch) / "openapi.json"
        client_path = Path(scratch) / "PlatformApiClient.g.cs"
        spec_path.write_text(spec_text, encoding="utf-8", newline="\n")
        subprocess.run(
            ["dotnet", "tool", "run", "nswag", "openapi2csclient",
             f"/input:{spec_path}", f"/output:{client_path}", *GENERATOR_OPTIONS],
            cwd=REVIT,
            check=True,
            stdout=subprocess.DEVNULL,
        )
        return honour_enum_member(lf(client_path.read_text(encoding="utf-8-sig")))


def differs(label: str, path: Path, wanted: str) -> bool:
    have = lf(path.read_text(encoding="utf-8")) if path.exists() else ""
    if have == wanted:
        return False
    diff = difflib.unified_diff(
        have.splitlines(), wanted.splitlines(), f"vendored {label}", f"generated {label}", lineterm="", n=1)
    lines = list(diff)
    print(f"{path.relative_to(REVIT.parent)} differs from what the spec generates:")
    print("\n".join(lines[:80]))
    if len(lines) > 80:
        print(f"... and {len(lines) - 80} more diff lines")
    return True


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--spec", default=SERVED_SPEC, help="the spec to generate from: a URL or a file")
    parser.add_argument("--check", action="store_true", help="fail when the vendored copy is not current")
    args = parser.parse_args(argv)

    spec_text = read_spec(args.spec)
    client_text = generate(spec_text)

    if args.check:
        stale = differs("openapi.json", VENDORED_SPEC, spec_text)
        stale = differs("PlatformApiClient.g.cs", VENDORED_CLIENT, client_text) or stale
        if stale:
            print(f"\nThe vendored Platform API client is not what {args.spec} generates. Run "
                  "`python revit/tools/platform-api/sync_platform_api.py` and commit the result.")
            return 1
        print(f"The vendored Platform API client is current with {args.spec}.")
        return 0

    GENERATED.mkdir(parents=True, exist_ok=True)
    VENDORED_SPEC.write_text(spec_text, encoding="utf-8", newline="\n")
    VENDORED_CLIENT.write_text(client_text, encoding="utf-8", newline="\n")
    print(f"Wrote {VENDORED_SPEC.relative_to(REVIT.parent)} and {VENDORED_CLIENT.relative_to(REVIT.parent)}.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
